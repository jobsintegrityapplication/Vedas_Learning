import logging
from uuid import uuid4

from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.middleware.cors import CORSMiddleware
from fastapi.openapi.utils import get_openapi
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException as StarletteHTTPException
from slowapi.errors import RateLimitExceeded
from slowapi.middleware import SlowAPIMiddleware
from slowapi import _rate_limit_exceeded_handler

from app.api import api_router
from app.core.config import get_settings
from app.core.logging import configure_logging
from app.core.rate_limit import limiter

configure_logging()
settings = get_settings()
settings.validate_runtime_secrets()

_log = logging.getLogger("veda.api")

app = FastAPI(
    title=settings.app_name,
    version="1.0.0",
    description=(
        "Vedas Learning API. Guru-approved scripture text is the source of truth. "
        "Pronunciation and Vedic svara scores are not returned unless a validated engine is configured. "
        "Authenticate with `Authorization: Bearer <access_token>`."
    ),
    docs_url="/docs" if settings.is_dev else None,
    redoc_url="/redoc" if settings.is_dev else None,
    openapi_tags=[
        {"name": "health", "description": "Liveness and readiness."},
        {"name": "auth", "description": "Registration, email OTP, login, refresh, logout."},
        {"name": "profile", "description": "Learner profile. Email is the verified account email."},
        {"name": "scriptures", "description": "Published scriptures, chapters and lesson counts."},
        {"name": "lessons", "description": "Guru-provided lessons. Text is not generated by the API."},
        {"name": "recordings", "description": "Learner audio metadata and evaluation capability status."},
        {"name": "progress", "description": "Practice history and dashboard counters."},
        {"name": "admin", "description": "RBAC-protected scripture, chapter, shloka, versioning, audit and publish APIs. Guru text is never auto-generated."},
    ],
)
app.state.limiter = limiter
app.add_exception_handler(RateLimitExceeded, _rate_limit_exceeded_handler)
app.add_middleware(SlowAPIMiddleware)
app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.cors_origin_list,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)
app.include_router(api_router)


@app.exception_handler(Exception)
async def unhandled_error(request: Request, exc: Exception):
    if isinstance(exc, StarletteHTTPException):
        return JSONResponse({"detail": exc.detail}, status_code=exc.status_code, headers=exc.headers)
    if isinstance(exc, RequestValidationError):
        return JSONResponse({"detail": exc.errors()}, status_code=422)
    if isinstance(exc, RateLimitExceeded):
        return _rate_limit_exceeded_handler(request, exc)
    _log.exception("Unhandled error on %s %s", request.method, request.url.path)
    return JSONResponse({"detail": "Internal server error"}, status_code=500)


@app.middleware("http")
async def security_headers(request: Request, call_next):
    request_id = request.headers.get("X-Request-ID") or uuid4().hex
    request.state.request_id = request_id
    response = await call_next(request)
    response.headers["X-Request-ID"] = request_id
    response.headers["X-Content-Type-Options"] = "nosniff"
    response.headers["X-Frame-Options"] = "DENY"
    response.headers["Referrer-Policy"] = "same-origin"
    if not get_settings().is_dev:
        response.headers["Cache-Control"] = "no-store"
    return response


def custom_openapi():
    if app.openapi_schema:
        return app.openapi_schema
    schema = get_openapi(
        title=app.title,
        version=app.version,
        description=app.description,
        routes=app.routes,
        tags=app.openapi_tags,
    )
    schema.setdefault("components", {}).setdefault("securitySchemes", {})
    schema["components"]["securitySchemes"]["BearerAuth"] = {
        "type": "http",
        "scheme": "bearer",
        "bearerFormat": "JWT",
    }
    app.openapi_schema = schema
    return schema


app.openapi = custom_openapi
